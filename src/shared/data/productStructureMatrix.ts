export function isRegisteredProductStructureByCodes(params: {
  structureType: ProductStructureType;
  selectedMaterialCodes: string[];
}): boolean {
  const { structureType, selectedMaterialCodes } = params;

  const matrix = PRODUCT_STRUCTURE_MATRIX[structureType];
  if (!matrix || matrix.size === 0) {
    return false;
  }

  const key = selectedMaterialCodes.join("|") + "|";
  return matrix.has(key);
}

export function getProductStructureTypeName(
  structureType: ProductStructureType,
): string {
  switch (structureType) {
    case "Monocapa":
      return "Estructura de 1 capa";
    case "Bilaminado":
      return "Estructura de 2 capas";
    case "Trilaminado":
      return "Estructura de 3 capas";
    case "Tetralaminado":
      return "Estructura de 4 capas";
    default:
      return "";
  }
}
